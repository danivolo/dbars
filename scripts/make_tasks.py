#!/usr/bin/env python
"""Write the task file for step 02: one line per chunk of ~20 galaxies, most expensive chunk first.

Galaxies (catalog table rows with an npz) are sorted by star-particle count and dealt round-robin into
ceil(N / per_chunk) chunks, so chunk costs are similar and every galaxy appears exactly once. Each line names its
galaxies explicitly (--sids), so a job does not need the catalog table. Lines use $WORKDIR (code checkout) and the
environment's python by absolute path (the shared template's `source activate gizmo_build` would shadow PATH).
Usage: python scripts/make_tasks.py --table ~/astro/runs/bars/manual/catalog/snap99.parquet --snap 99 \
           [--per-chunk 20] [--config-path '$WORKDIR/config/cluster.yaml'] [--out cluster/tasks/diag_snap99.txt]
"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from dbars.runio import atomic_write_text, chunk_sids
from dbars.sample import ordered_sids

PY = "$HOME/astro/envs/bars/bin/python"


def make_lines(df, snap, per_chunk=20, config_path="$WORKDIR/config/cluster.yaml", python=PY, max_sids=None):
    sids = ordered_sids(df)
    if max_sids:
        sids = sids[:max_sids]
    n = max(int(np.ceil(len(sids) / per_chunk)), 1) if sids else 0
    cost = dict(zip(df["sid"].astype(int), df["n_star"].astype(int)))
    chunks = [chunk_sids(sids, i, n) for i in range(1, n + 1)]
    order = sorted(range(n), key=lambda k: -sum(cost[s] for s in chunks[k]))
    lines = []
    for k in order:
        c = chunks[k]
        lines.append(f"{python} $WORKDIR/scripts/02_galaxy_diagnostics.py --config {config_path} --snap {snap} "
                     f"--sids {','.join(map(str, c))} --log-name diag_snap{snap}_c{k + 1:03d}")
    return lines, chunks, [sum(cost[s] for s in chunks[k]) for k in order]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--table", required=True)
    p.add_argument("--snap", type=int, required=True)
    p.add_argument("--per-chunk", type=int, default=20)
    p.add_argument("--max-galaxies", type=int, default=None, help="only the N most expensive (dry runs)")
    p.add_argument("--config-path", default="$WORKDIR/config/cluster.yaml")
    p.add_argument("--python", default=PY)
    p.add_argument("--out", default=None, help="default cluster/tasks/diag_snap<SNAP>.txt in this repo")
    args = p.parse_args(argv)
    df = pd.read_parquet(args.table)
    lines, chunks, costs = make_lines(df, args.snap, args.per_chunk, args.config_path, args.python, args.max_galaxies)
    out = Path(args.out) if args.out else Path(__file__).resolve().parents[1] / "cluster/tasks" / f"diag_snap{args.snap}.txt"
    ngal = sum(len(c) for c in chunks)
    head = [
            f"# bars step 02, snap {args.snap}: {ngal} galaxies in {len(lines)} tasks (~{args.per_chunk} each), "
            f"longest first; star particles per task {max(costs, default=0)}..{min(costs, default=0)}",
            f"# generated by scripts/make_tasks.py from {args.table}"]
    atomic_write_text(out, "\n".join(head + lines) + "\n")
    print(f"{len(lines)} tasks, {ngal} galaxies -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
